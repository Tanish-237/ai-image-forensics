// The page talks to the API on the same server, or to the address given as ?api=... (used by the hosted copy).
const API_BASE = (new URLSearchParams(location.search).get("api") || "").replace(/\/$/, "");

const fileInput = document.getElementById("file");
const drop = document.getElementById("drop");
const canvas = document.getElementById("preview");
const ctx = canvas.getContext("2d");

const views = {
  empty: document.getElementById("result-empty"),
  busy: document.getElementById("result-busy"),
  error: document.getElementById("result-error"),
  body: document.getElementById("result-body"),
};

function show(name) {
  for (const [key, el] of Object.entries(views)) el.hidden = key !== name;
}

function cssVar(name) {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim();
}

function colourFor(p) {
  return cssVar(p >= 0.5 ? "--ai" : "--real");
}

function percent(p) {
  return `${(p * 100).toFixed(1)}%`;
}

let currentImage = null;
let currentFile = null;
let currentResult = null;

function selectedTiles() {
  return document.querySelector('input[name="tiles"]:checked').value;
}

function drawImage(img, tiles, analysedSize) {
  const maxWidth = drop.clientWidth - 32;
  const scale = Math.min(1, maxWidth / img.width, 520 / img.height);
  canvas.width = Math.round(img.width * scale);
  canvas.height = Math.round(img.height * scale);
  ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
  if (!tiles) return;

  // tiles are in the coordinates of the analysed image, which may have been enlarged
  const sx = canvas.width / analysedSize[0];
  const sy = canvas.height / analysedSize[1];
  for (const t of tiles) {
    const colour = colourFor(t.probability_ai);
    const strength = Math.abs(t.probability_ai - 0.5) * 2;
    ctx.fillStyle = colour;
    ctx.globalAlpha = 0.12 + 0.33 * strength;
    ctx.fillRect(t.x * sx, t.y * sy, t.size * sx, t.size * sy);
    ctx.globalAlpha = 1;
    ctx.strokeStyle = colour;
    ctx.lineWidth = 2;
    ctx.strokeRect(t.x * sx + 1, t.y * sy + 1, t.size * sx - 2, t.size * sy - 2);
    const label = `${Math.round(t.probability_ai * 100)}`;
    ctx.font = "600 12px Inter, sans-serif";
    const w = ctx.measureText(label).width + 10;
    ctx.fillStyle = "rgba(0, 0, 0, 0.6)";
    ctx.fillRect(t.x * sx + 4, t.y * sy + 4, w, 18);
    ctx.fillStyle = "#ffffff";
    ctx.fillText(label, t.x * sx + 9, t.y * sy + 17);
  }
}

const BASIS = {
  credentials: "Decided by the file's signed Content Credentials.",
  label: "Decided by an AI label in the file's metadata (unsigned).",
  pixels: "Decided by the pixel detector, because the file carries no usable provenance information.",
  uncertain: "The pixel score is between 40% and 60%, where most of the detector's mistakes fell in our tests, so the lean is only a weak hint. The file carries no usable provenance information.",
};

const DECIDED_BY = { credentials: "Content Credentials", label: "AI label", pixels: "Pixel detector" };

function verdictText(result) {
  if (result.verdict !== "Uncertain") return result.verdict;
  return `Not sure, leans ${result.leans === "AI-generated" ? "AI" : "real"}`;
}

function verdictColour(result) {
  if (result.verdict === "Uncertain") return cssVar("--warn");
  return colourFor(result.verdict === "AI-generated" ? 1 : 0);
}

function formatBytes(n) {
  return n >= 1048576 ? `${(n / 1048576).toFixed(1)} MB` : `${Math.round(n / 1024)} KB`;
}

function formatDate(iso) {
  const d = new Date(iso);
  return isNaN(d) ? "" : ` on ${d.toLocaleDateString(undefined, { day: "numeric", month: "short", year: "numeric" })}`;
}

function evidenceItems(p) {
  const items = [];
  const c = p.credentials;
  if (c) {
    const who = `${c.tool ? `Made with ${c.tool}. ` : ""}Signed by ${c.signer || "an unknown signer"}${formatDate(c.signed_at)}.`;
    const trust = c.state === "Trusted" ? " The signature is valid and the signer is on the C2PA trust list."
      : " The signature is valid, but the signer is not on the C2PA trust list.";
    if (c.state === "Invalid") {
      items.push(["warn", "!", "Content Credentials do not match the image",
        `${who} The check failed (${c.problems[0] || "invalid signature"}), so they were not used.`]);
    } else if (c.ai) {
      items.push(["ai", "AI", "Content Credentials: generated by AI", who + trust]);
    } else if (c.camera) {
      items.push([c.state === "Trusted" ? "real" : "neutral", "\u2713", "Content Credentials: captured by a camera", who + trust]);
    } else {
      items.push(["neutral", "i", "Content Credentials found", `${who}${trust} Source: ${c.source_types.join(", ") || "not stated"}.`]);
    }
  } else {
    items.push(["neutral", "\u2013", "No Content Credentials",
      "ChatGPT, Gemini and some other generators and cameras sign their images. Messaging apps, screenshots and most editors remove the signature."]);
  }
  if (p.label) items.push(["ai", "AI", "AI label in the metadata", `Unsigned ${p.label}.`]);
  if (p.camera) items.push(["neutral", "i", `Camera EXIF: ${p.camera}`, "Unsigned and easy to edit, so not used for the verdict."]);
  return items;
}

function render(result) {
  const verdict = document.getElementById("verdict");
  verdict.textContent = verdictText(result);
  verdict.style.color = verdictColour(result);
  document.getElementById("basis").textContent = BASIS[result.verdict === "Uncertain" ? "uncertain" : result.decided_by];

  const list = document.getElementById("provenance");
  list.innerHTML = "";
  for (const [kind, mark, title, detail] of evidenceItems(result.provenance)) {
    const li = document.createElement("li");
    li.className = kind;
    li.innerHTML = '<span class="mark"></span><strong></strong><span class="detail"></span>';
    li.children[0].textContent = mark;
    li.children[1].textContent = title;
    li.children[2].textContent = detail;
    list.appendChild(li);
  }

  const p = result.pixels.probability_ai;
  document.getElementById("meter-fill").style.left = `${p * 100}%`;
  document.getElementById("prob").textContent = `AI score ${percent(p)}`;
  document.getElementById("pixel-name").textContent =
    `${result.pixels.name}. Calibrated so that 50% is the decision line; scores in the dashed range (40–60%) are reported as uncertain.`;

  const familiesBlock = document.getElementById("families-block");
  const families = document.getElementById("families");
  families.innerHTML = "";
  familiesBlock.hidden = !result.families;
  for (const f of (result.families || []).slice(0, 3)) {
    const li = document.createElement("li");
    li.innerHTML = '<span></span><span class="value"></span><div class="track"><div class="fill"></div></div>';
    li.children[0].textContent = f.family;
    li.children[1].textContent = percent(f.probability);
    const fill = li.querySelector(".fill");
    fill.style.width = `${f.probability * 100}%`;
    fill.style.background = cssVar("--ai");
    families.appendChild(li);
  }

  document.getElementById("notes").textContent = result.notes.join(" ");
  const [w, h] = result.original_size;
  document.getElementById("meta").textContent =
    `${w} × ${h} pixels · ${result.tiles.length} tiles analysed at full resolution · numbers on tiles are calibrated pixel scores (%) · ${result.seconds} s`;
  if (currentImage) {
    drawImage(currentImage, result.tiles, result.analysed_size);
  } else {
    document.getElementById("preview-wrap").hidden = true;
    const empty = document.getElementById("drop-empty");
    empty.hidden = false;
    empty.innerHTML = "<strong>Analysed</strong><span class='muted'>This browser cannot preview this file format, so the tile map is not shown.</span>";
  }
  show("body");
}

async function request(file, share) {
  const form = new FormData();
  form.append("file", file);
  form.append("tiles", selectedTiles());
  if (share) form.append("share", "true");
  const response = await fetch(`${API_BASE}/api/analyze`, { method: "POST", body: form });
  const data = await response.json();
  if (!response.ok) throw new Error(data.detail || "The image could not be analysed.");
  return data;
}

function credentialsText(c) {
  if (!c) return "None";
  if (c.state === "Invalid") return "Present, but broken";
  return `${c.ai ? "Signed: made by AI" : c.camera ? "Signed: camera" : "Signed"}${c.tool ? ` (${c.tool})` : ""}`;
}

function renderCompare(before, after) {
  const rows = [
    ["Verdict", verdictText],
    ["Decided by", (r) => DECIDED_BY[r.decided_by]],
    ["Content Credentials", (r) => credentialsText(r.provenance.credentials)],
    ["Pixel AI score", (r) => percent(r.pixels.probability_ai)],
    ["Image size", (r) => r.original_size.join(" × ")],
    ["File size", (r) => formatBytes(r.file_bytes)],
  ];
  const body = document.querySelector("#compare tbody");
  body.innerHTML = "";
  for (const [name, value] of rows) {
    const tr = document.createElement("tr");
    for (const text of [name, value(before), value(after)]) {
      const cell = document.createElement(tr.children.length ? "td" : "th");
      cell.textContent = text;
      tr.appendChild(cell);
    }
    if (name === "Verdict") {
      tr.children[1].style.color = verdictColour(before);
      tr.children[2].style.color = verdictColour(after);
    }
    body.appendChild(tr);
  }
  document.getElementById("compare").hidden = false;
}

function resetShare() {
  document.getElementById("compare").hidden = true;
  document.getElementById("share-error").hidden = true;
}

async function analyse(file) {
  if (fileInput.disabled) return;
  resetShare();
  show("busy");
  document.getElementById("drop-empty").hidden = true;
  document.getElementById("preview-wrap").hidden = false;

  currentFile = file;
  currentImage = null;
  try {
    currentImage = await createImageBitmap(file, { imageOrientation: "from-image" });
    drawImage(currentImage);
  } catch {
    ctx.clearRect(0, 0, canvas.width, canvas.height); // e.g. HEIC in browsers that cannot display it
  }

  try {
    currentResult = await request(file, false);
    render(currentResult);
  } catch (err) {
    views.error.textContent = err.message;
    show("error");
  }
}

fileInput.addEventListener("change", () => fileInput.files[0] && analyse(fileInput.files[0]));
for (const type of ["dragenter", "dragover"]) {
  drop.addEventListener(type, (e) => { e.preventDefault(); drop.classList.add("over"); });
}
for (const type of ["dragleave", "drop"]) {
  drop.addEventListener(type, (e) => { e.preventDefault(); drop.classList.remove("over"); });
}
drop.addEventListener("drop", (e) => e.dataTransfer.files[0] && analyse(e.dataTransfer.files[0]));
for (const radio of document.querySelectorAll('input[name="tiles"]')) {
  radio.addEventListener("change", () => currentFile && analyse(currentFile));
}

const shareButton = document.getElementById("share-btn");
shareButton.addEventListener("click", async () => {
  if (!currentFile || !currentResult) return;
  const label = shareButton.textContent;
  shareButton.disabled = true;
  shareButton.textContent = "Analysing the shared copy…";
  resetShare();
  try {
    renderCompare(currentResult, await request(currentFile, true));
  } catch (err) {
    const error = document.getElementById("share-error");
    error.textContent = err.message;
    error.hidden = false;
  } finally {
    shareButton.disabled = false;
    shareButton.textContent = label;
  }
});

for (const button of document.querySelectorAll(".sample")) {
  button.addEventListener("click", async () => {
    if (fileInput.disabled) return;
    try {
      const response = await fetch(`/static/samples/${button.dataset.file}`);
      if (!response.ok) throw new Error();
      const blob = await response.blob();
      document.getElementById("try").scrollIntoView();
      analyse(new File([blob], button.dataset.file, { type: blob.type }));
    } catch {
      views.error.textContent = "The sample image could not be loaded.";
      show("error");
    }
  });
}

async function checkServer() {
  try {
    const response = await fetch(`${API_BASE}/api/info`);
    if (!response.ok) throw new Error();
    const info = await response.json();
    if (info.public_link) {
      document.getElementById("qr").src = `${API_BASE}/api/qr`;
      document.getElementById("phone").hidden = false;
    }
  } catch {
    fileInput.disabled = true;
    document.querySelector(".samples").classList.add("offline");
    drop.classList.add("offline");
    document.getElementById("drop-empty").innerHTML =
      "<strong>The live detector is offline</strong><span class='muted'>It runs on our own computer and is switched on during demonstrations. The results of our experiments are below.</span>";
    views.empty.textContent = "Analysis is available when the detector is running.";
  }
}

checkServer();
